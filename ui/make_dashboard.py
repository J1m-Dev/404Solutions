"""Builds site/dashboard.html (the DOM control room) from the team's own site/index.html.

Run from the repository root after index.html changes:   python3 ui/make_dashboard.py

It copies each of index.html's sections, unchanged and with the same ids, onto pages of the control room, so
assets/app.js runs exactly as written. It then checks that every element app.js looks up by id is on the page.
Nothing in site/index.html, site/assets/app.js or site/assets/model.js is modified.
"""
import re, sys, time, pathlib
ROOT = pathlib.Path(__file__).resolve().parent.parent / "site"
src = (ROOT / "index.html").read_text()

def block(tag, ident):
    """The whole element <tag id=ident ...>...</tag>, exactly as written."""
    m = re.search(r'<%s\b[^>]*\bid="%s"[^>]*>' % (tag, ident), src)
    if not m: sys.exit("index.html no longer has <%s id=%s>" % (tag, ident))
    end = src.index("</%s>" % tag, m.start()) + len(tag) + 3
    return src[m.start():end]

hero, now, forecast, trust, atlas, track, stakes = (block("section", i) for i in ["hero", "now", "forecast", "trust", "atlas", "track", "stakes"])
hero = hero.replace("FluSentinel", "DOM")   # the product's name since 10 Oct; the sentence is otherwise the team's own
more = "\n".join(block("details", i) for i in ["proof", "dengue", "trendFold", "sim", "history", "guide"])
dlg = block("dialog", "dlg")
footer = re.search(r"<footer>.*?</footer>", src, re.S).group(0)
now_inner = now[now.index(">") + 1:now.rindex("</section>")]          # his alert card, summary, actions and plan
split = atlas.index('  <div class="grid2">\n    <div>\n      <h3>Selangor districts')
map_part, beds_part = atlas[:split] + "</section>", atlas[split:atlas.rindex("</section>")]

V = str(int(time.time()))   # stamped on our own files' addresses, so a browser never runs an older copy after a deploy
def page(ident, title, lead, body, tools=""):
    """An inner page in the kit (assets/room.css, "THE KIT"): the first line, an empty board for its tiles, then the team's own section."""
    return f'''
<section class="page" id="p-{ident}" data-page="{ident}">
  <header class="phead"><p class="when"><b>{title}</b> · <span id="w-{ident}">{lead}</span></p>{tools and f'<div class="tools">{tools}</div>'}</header>
  <div class="board" id="b-{ident}"></div>
{body}
</section>'''
def door(ident, name, ext="png", cls=""):
    return f'<a href="#/{ident}" data-go="{ident}"{cls and f' class="{cls}"'}><img src="assets/img/ic-{ident}.{ext}" alt="" width="38" height="38"><span>{name}</span></a>'

