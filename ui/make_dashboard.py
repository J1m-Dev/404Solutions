# ---- checks: every id app.js asks for must be on the page, once ----
js = (ROOT / "assets" / "app.js").read_text()
asked = set(re.findall(r'\$\("([A-Za-z0-9_\-]+)"\)', js)) | {"ly_" + k for k in ["state", "shade", "heat", "hot", "government", "private", "clinic"]} | {"n_" + k for k in ["government", "private", "clinic"]}
asked |= {i for _, i in re.findall(r'\[(render\w+), "(\w+)"\]', js)}
made_by_app = {i for i in asked if i not in re.findall(r'id="([^"]+)"', src)}       # ids app.js creates itself (also absent from index.html)
have = re.findall(r'id="([^"]+)"', html)
missing = sorted(i for i in asked - made_by_app if i not in have)
dup = sorted({i for i in have if have.count(i) > 1})
his = set(re.findall(r'id="([^"]+)"', src)) - {"now", "more"}
lost = sorted(i for i in his if i not in have)
print(f"dashboard.html written. ids app.js looks up: {len(asked)} (it creates {len(made_by_app)} itself: {sorted(made_by_app)})")
print("missing on our page:", missing, "| duplicated:", dup, "| in his page but not ours:", lost)
if missing or dup: sys.exit(1)
